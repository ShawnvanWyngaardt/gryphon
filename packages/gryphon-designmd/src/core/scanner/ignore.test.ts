import { describe, expect, it } from 'vitest';

import { isSuppressed, parseDirective } from './ignore.js';

describe('parseDirective (AC2.6)', () => {
  it.each([
    ['gryphon-ignore-next-line', 'next-line'],
    [' gryphon-ignore-next-line ', 'next-line'],
    ['gryphon-ignore-next-line: brand partner colour', 'next-line'],
    ['gryphon-ignore-next-line because of the logo', 'next-line'],
    ['gryphon-ignore-file', 'file'],
    ['gryphon-ignore-file: generated by the icon tool', 'file'],
    ['gryphon-ignore-next', null],
    ['gryphon-ignore-next-lines', null],
    ['Gryphon-Ignore-File', null],
    ['please gryphon-ignore-file', null],
    ['', null],
  ] as const)('%j is %s', (text, expected) => {
    expect(parseDirective(text)).toBe(expected);
  });
});

describe('isSuppressed', () => {
  it('is true for a listed line, or for every line when the file is ignored', () => {
    expect(isSuppressed({ file: false, lines: [3, 7] }, 7)).toBe(true);
    expect(isSuppressed({ file: false, lines: [3, 7] }, 4)).toBe(false);
    expect(isSuppressed({ file: true, lines: [] }, 99)).toBe(true);
  });
});
